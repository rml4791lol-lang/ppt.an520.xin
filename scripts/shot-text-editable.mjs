import { createRequire } from 'node:module';
const require = createRequire('/Users/an/Documents/AI PPT/anppt-app/node_modules/');
const { chromium } = require('playwright');

const SESSION = process.argv[2];
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
await ctx.addCookies([{ name: 'anppt_v2_session', value: SESSION, url: 'http://localhost:3120' }]);
const page = await ctx.newPage();
await page.goto('http://localhost:3120/deck/deck_b435069a773cd84e88f99a20', { waitUntil: 'networkidle' });
await page.waitForTimeout(2500);
const bar = page.locator('text=下载文字可编辑版').first();
console.log('下载文字可编辑版存在:', (await bar.count()) > 0);
await bar.scrollIntoViewIfNeeded();
await page.waitForTimeout(300);
await page.screenshot({ path: 'output/playwright/text-editable-bar.png' });
await page.getByRole('button', { name: '重新转换' }).last().click();
await page.waitForTimeout(700);
await page.screenshot({ path: 'output/playwright/text-editable-modal.png' });
await browser.close();
console.log('done');
